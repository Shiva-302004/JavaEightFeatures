package com.gevernova.javaEightfeatures.DayThree.Problemsetone.Problem4;

class Rectangle {
    int length, width;

    Rectangle(int length, int width) {
        this.length = length;
        this.width = width;
    }

    public String toString() {
        return "Rectangle [length=" + length + ", width=" + width + "]";
    }
}
